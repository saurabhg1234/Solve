"""Check client proposal packaging; visual inspection and factual review stay separate.

Usage: python client_proposal_preflight.py --word proposal.docx --slides deck.pptx
       --brand-logo mindmap.png --client-logo client.png [--output checks.json]
Only reads local Office files. Never calls a model or uploads source material.
"""
from pathlib import Path
from zipfile import ZipFile
from xml.etree import ElementTree as ET
import argparse
import hashlib
import json
import posixpath
import re

W='http://schemas.openxmlformats.org/wordprocessingml/2006/main'
A='http://schemas.openxmlformats.org/drawingml/2006/main'
R='http://schemas.openxmlformats.org/officeDocument/2006/relationships'
P='http://schemas.openxmlformats.org/presentationml/2006/main'
INTERNAL=re.compile(r'\b(?:notes indicate|meeting notes|manual proposal|supplied reference|review draft|revision basis|independent[ -]qc|source hash|ai[ -]generated|generated by (?:ai|codex|claude)|drafted by (?:ai|codex|claude)|zora|codex)\b',re.I)

def digest(data):return hashlib.sha256(data).hexdigest()
def text(root):return ' '.join(e.text or '' for e in root.iter() if e.tag in (f'{{{W}}}t',f'{{{A}}}t'))
def image_hashes(z,part,root):
 relpath=posixpath.join(posixpath.dirname(part),'_rels',posixpath.basename(part)+'.rels')
 if relpath not in z.namelist():return []
 rels={r.attrib['Id']:r.attrib for r in ET.fromstring(z.read(relpath))}
 result=[]
 for blip in root.iter(f'{{{A}}}blip'):
  rel=rels.get(blip.get(f'{{{R}}}embed'))
  if not rel or rel.get('TargetMode')=='External':continue
  target=rel['Target'];path=target.lstrip('/') if target.startswith('/') else posixpath.normpath(posixpath.join(posixpath.dirname(part),target))
  result.append(digest(z.read(path)))
 return result

def ordered_slides(z):
 """Follow presentation order, which can differ from slide file numbering."""
 rels={r.attrib['Id']:r.attrib for r in ET.fromstring(z.read('ppt/_rels/presentation.xml.rels'))}
 result=[]
 for el in ET.fromstring(z.read('ppt/presentation.xml')).iter(f'{{{P}}}sldId'):
  rel=rels[el.get(f'{{{R}}}id')]
  if rel.get('TargetMode')=='External':raise ValueError('External slide relationship')
  target=rel['Target'];result.append(target.lstrip('/') if target.startswith('/') else posixpath.normpath(posixpath.join('ppt',target)))
 return result

def inspect(word,slides,brand,client):
 errors=[];result={'checks':'Office packaging and client-language preflight; not independent QC or visual approval'}
 bh,ch=digest(brand.read_bytes()),digest(client.read_bytes())
 def need(ok,message):
  if not ok:errors.append(message)
 def language(value,location):
  hits=sorted(set(m.group(0) for m in INTERNAL.finditer(value)))
  need(not hits,f'{location}: internal authoring language: {hits}')
 if word:
  with ZipFile(word) as z:
   root=ET.fromstring(z.read('word/document.xml'));body=root.find(f'{{{W}}}body');cover=ET.Element('cover')
   for el in body:
    if any(b.get(f'{{{W}}}type')=='page' for b in el.iter(f'{{{W}}}br')):break
    cover.append(el)
   cover_images=image_hashes(z,'word/document.xml',cover)
   need(bh in cover_images,'Word cover: official Mindmap logo missing')
   need(ch in cover_images,'Word cover: official client logo missing')
   need(any(h not in (bh,ch) for h in cover_images),'Word cover: separate cover graphic missing')
   need(bool(text(cover).strip()),'Word cover: title/content missing')
   need(bool(re.search(r'about\s+mindmap',text(root),re.I)),'Word: About Mindmap section missing')
   rels={x.attrib['Id']:x.attrib['Target'] for x in ET.fromstring(z.read('word/_rels/document.xml.rels'))}
   inherited={};sections=list(root.iter(f'{{{W}}}sectPr'))
   for i,section in enumerate(sections):
    refs={r.get(f'{{{W}}}type'):r.get(f'{{{R}}}id') for r in section.findall(f'{{{W}}}headerReference')};inherited.update(refs)
    types=['default']+(['even'] if 'even' in inherited else [])
    # First page may use the branded cover itself; later section first-page headers need the logo.
    if i and section.find(f'{{{W}}}titlePg') is not None:types.append('first')
    for typ in types:
     rid=inherited.get(typ);target=rels.get(rid,'');part=posixpath.normpath(posixpath.join('word',target))
     need(bool(target),f'Word section {i+1}: {typ} header missing')
     if target:need(bh in image_hashes(z,part,ET.fromstring(z.read(part))),f'Word section {i+1}: Mindmap logo absent from {typ} header')
   for name in z.namelist():
    if name.startswith('word/') and name.endswith('.xml') and any(x in name for x in ('document','header','footer','comments','footnote','endnote')):language(text(ET.fromstring(z.read(name))),name)
   need('word/comments.xml' not in z.namelist(),'Word: review comments must be removed')
   need(not list(root.iter(f'{{{W}}}ins')) and not list(root.iter(f'{{{W}}}del')),'Word: tracked revisions must be resolved')
   result['word']={'sections':len(sections),'coverImages':len(cover_images),'svgFigures':sum(n.startswith('word/media/') and n.endswith('.svg') for n in z.namelist())}
 if slides:
  with ZipFile(slides) as z:
   parts=ordered_slides(z)
   alltext=[];connectors=0
   for i,part in enumerate(parts):
    root=ET.fromstring(z.read(part));images=image_hashes(z,part,root);value=text(root);alltext.append(value);language(value,part)
    need(bh in images,f'PowerPoint slide {i+1}: Mindmap logo missing')
    if i==0:
     need(ch in images,'PowerPoint cover: client logo missing');need(any(h not in (bh,ch) for h in images),'PowerPoint cover: cover graphic missing')
    connectors+=len(list(root.iter(f'{{{P}}}cxnSp')))
   need(bool(re.search(r'about\s+mindmap',' '.join(alltext),re.I)),'PowerPoint: About Mindmap section missing')
   combined=' '.join(alltext)
   for label,pattern in [('services',r'what we do|our capabilities|services (?:and|&) practices'),('geographic presence',r'global footprint|geographic presence|our presence|where we work'),('customers',r'our customers|selected customers|enterprise customers')]:
    need(bool(re.search(pattern,combined,re.I)),f'PowerPoint: company {label} section missing')
   closing=alltext[-1] if alltext else ''
   need(bool(re.search(r'thank you|let[’\']s (?:build|work|connect)',closing,re.I)),'PowerPoint: final closing slide missing')
   need('mindmapdigital.ai' in closing.lower(),'PowerPoint: verified company contact/site missing from final slide')
   for n in z.namelist():
    if re.fullmatch(r'ppt/notesSlides/notesSlide\d+\.xml',n):language(text(ET.fromstring(z.read(n))),n)
   need(not any(n.startswith('ppt/comments/') for n in z.namelist()),'PowerPoint: review comments must be removed')
   result['powerpoint']={'slides':len(parts),'nativeConnectors':connectors}
 result['errors']=errors;result['passed']=not errors;return result

if __name__=='__main__':
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--word',type=Path);ap.add_argument('--slides',type=Path);ap.add_argument('--brand-logo',required=True,type=Path);ap.add_argument('--client-logo',required=True,type=Path);ap.add_argument('--output',type=Path);a=ap.parse_args()
 if not a.word and not a.slides:ap.error('Provide --word and/or --slides')
 result=inspect(a.word,a.slides,a.brand_logo,a.client_logo)
 if a.output:a.output.write_text(json.dumps(result,indent=2))
 print(json.dumps(result,indent=2));raise SystemExit(0 if result['passed'] else 1)
